import type { ItemKind } from '@/lib/estimate'
import { T } from '@/i18n'

export interface PriceEntry {
  key: string
  name: string
  unit: string
  price: number
  kind: ItemKind
  group: string
}

const m = (group: string, key: string, name: string, unit: string, price: number): PriceEntry => ({
  key, name, unit, price, kind: 'material', group,
})
const w = (key: string, name: string, unit: string, price: number): PriceEntry => ({
  key, name, unit, price, kind: 'work', group: T('Работы'),
})
const t = (key: string, name: string, unit: string, price: number, kind: ItemKind = 'transport'): PriceEntry => ({
  key, name, unit, price, kind, group: T('Техника и доставка'),
})

